/**
 * Each model call's timings, measured from its stream the same way for
 * every adapter, as assistant-ui measures them: when the call starts, its
 * first generated token, and its last. Token counts come from the adapter's
 * usage, when it reports any.
 */
import type { ChatMiddleware, TokenUsage } from "@tanstack/ai"

import type { GenerationStats } from "./generation-stats"

/** What the model generated: its first one is the call's first token, its last the end of decoding. */
const GENERATED = new Set<string>([
  "TEXT_MESSAGE_CONTENT",
  "REASONING_MESSAGE_CONTENT",
  "TOOL_CALL_START",
  "TOOL_CALL_ARGS"
])

/**
 * A model call's timings as measured from its stream, in `performance.now()`
 * ms: when it started, and when it generated its first and last output.
 */
export type CallClock = { start: number; first?: number; last?: number }

/**
 * A model call's stats: its token counts, if the adapter reports them, and
 * its timings measured from the stream (`clock`). The first token's time,
 * from the call's start, also stands for reading the prompt (prompt speed
 * divides the tokens not cached by it, where the adapter says how many were
 * cached); tokens per second divides the tokens
 * generated by the whole stream, from sending the prompt to the last output,
 * as assistant-ui measures it: the same for every runtime, whenever the page
 * gets the text.
 */
export function statsFromUsage(
  usage: TokenUsage | undefined,
  clock?: CallClock
): GenerationStats {
  const cachedTokens = usage?.promptTokensDetails?.cachedTokens
  const firstTokenMs = clock?.first !== undefined ? clock.first - clock.start : undefined
  const streamMs = clock?.last !== undefined ? clock.last - clock.start : undefined
  return {
    ...(usage && { inputTokens: usage.promptTokens, outputTokens: usage.completionTokens }),
    // 0 too: the whole prompt was read. Left out where the adapter can't say.
    ...(cachedTokens !== undefined && { cachedTokens }),
    ...(firstTokenMs !== undefined && { firstTokenMs, promptMs: firstTokenMs }),
    ...(streamMs !== undefined && { streamMs })
  }
}

/** Records a model call's stats in a chat's reply, by the call's key. */
export type RecordGeneration = (threadId: string, key: string, stats: GenerationStats) => void

/**
 * One reply's middleware: its calls' clocks live here, for this `chat()`
 * only. A call's timings are recorded when it finishes, whether or not the
 * adapter reports usage; usage, when it comes, replaces them with the
 * call's token counts and the same timings. A reply that calls tools makes
 * one call per step.
 */
export function replyStatsMiddleware(record: RecordGeneration): ChatMiddleware {
  const clocks = new Map<string, CallClock>()
  const keyOf = (ctx: { runId: string; iteration: number }) => `${ctx.runId}:${ctx.iteration}`
  return {
    name: "reply-stats",
    // The step's own index: `ctx.iteration` still holds the last step's
    // until the model is called.
    onIteration: (ctx, { iteration }) => {
      clocks.set(keyOf({ runId: ctx.runId, iteration }), { start: performance.now() })
    },
    onChunk: (ctx, chunk) => {
      const key = keyOf(ctx)
      const clock = clocks.get(key)
      if (!clock) return
      if (chunk.type === "RUN_FINISHED") {
        record(ctx.threadId, key, statsFromUsage(undefined, clock))
        return
      }
      if (!GENERATED.has(chunk.type)) return
      clock.first ??= performance.now()
      clock.last = performance.now()
    },
    onUsage: (ctx, usage) => {
      const key = keyOf(ctx)
      record(ctx.threadId, key, statsFromUsage(usage, clocks.get(key)))
    }
  }
}
