import fs from 'fs';
import { create, globals } from 'webgpu';
Object.assign(globalThis, globals);
Object.defineProperty(globalThis, 'navigator', { value: { gpu: create([]) }, configurable: true });
const ort = await import('./ortweb/ort.webgpu.mjs');
ort.env.wasm.numThreads = 1; ort.env.wasm.wasmPaths = new URL('./ortweb/', import.meta.url).href;
const m = process.argv[2];
const s = await ort.InferenceSession.create(fs.readFileSync(m), { executionProviders: ['webgpu'], externalData: [{ path: 'model_q4f16.onnx_data', data: new Uint8Array(fs.readFileSync(m + '_data')) }] });
console.log(JSON.stringify((s.inputMetadata ?? []).slice(0, 6)));
process.exit(0);
