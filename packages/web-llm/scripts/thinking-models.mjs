// Writes src/thinking-models.ts: the catalog's chat models whose chat
// template has Qwen's thinking switch (`enable_thinking`), read from each
// model's own tokenizer_config.json (or chat_template.jinja) on Hugging Face.
// WebLLM's catalog doesn't say which models think. Run it again when the
// @mlc-ai/web-llm version changes:
//   node packages/web-llm/scripts/thinking-models.mjs
import { writeFile } from "node:fs/promises"
import { ModelType, prebuiltAppConfig } from "@mlc-ai/web-llm"

const records = prebuiltAppConfig.model_list.filter((record) => record.model_type !== ModelType.embedding)

/** A model's chat template, or "" when it has none. */
async function chatTemplate(record) {
  const base = `${record.model.replace(/\/$/, "")}/resolve/main`
  const config = await fetch(`${base}/tokenizer_config.json`)
  if (config.ok) {
    const template = (await config.json()).chat_template
    if (typeof template === "string") return template
    if (Array.isArray(template)) return template.map((entry) => entry.template ?? "").join("\n")
  }
  const jinja = await fetch(`${base}/chat_template.jinja`)
  return jinja.ok ? jinja.text() : ""
}

const thinking = []
const queue = [...records]
await Promise.all(
  Array.from({ length: 8 }, async () => {
    for (let record = queue.shift(); record; record = queue.shift()) {
      if ((await chatTemplate(record)).includes("enable_thinking")) thinking.push(record.model_id)
    }
  })
)
const order = new Map(records.map((record, i) => [record.model_id, i]))
thinking.sort((a, b) => order.get(a) - order.get(b))

const { version } = (await import("@mlc-ai/web-llm/package.json", { with: { type: "json" } })).default
await writeFile(
  new URL("../src/thinking-models.ts", import.meta.url),
  `// Generated by scripts/thinking-models.mjs from @mlc-ai/web-llm ${version}'s catalog: don't edit.
/** The catalog's chat models whose chat template has the thinking switch (\`enable_thinking\`). */
export const THINKING_MODELS: ReadonlyArray<string> = ${JSON.stringify(thinking, null, 2)}
`
)
console.log(`${thinking.length} of ${records.length} models have the switch:\n${thinking.join("\n")}`)
