/** Prepare an explicit, temporary manual browser benchmark on an existing Vite origin. */
import { readFile, writeFile, mkdtemp, mkdir, cp, rm, access } from "node:fs/promises"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"
import { dirname, resolve, relative, isAbsolute, join } from "node:path"
import { tmpdir } from "node:os"

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, "../../..")
const app = resolve(repo, process.argv[2] ?? "")
const rel = relative(repo, app)
if (!process.argv[2] || !rel || rel.startsWith("..") || isAbsolute(rel)) {
  throw new Error("Usage: node packages/transformers-js/bench/prepare-cache-qa.mjs <vite-app-directory> [baseline-ref|--clean]")
}
const pages = [
  ["__adapter-cache-qa.html", "cache-template.html"],
  ["__native-tools-qa.html", "cache-tools-template.html"],
  ["__prefix-numerics-qa.html", "cache-numerics-template.html"],
  ["__simple-tools-qa.html", "cache-simple-tools-template.html"],
  ["__single-prompts-qa.html", "cache-single-prompts-template.html"]
]
const htmlFiles = pages.map(([name]) => join(app,name))
const packages = ["webgl", "transformers-js", "structured-output"]
const copies = packages.map(name => join(repo, "packages", name, ".cache-qa-baseline"))
const marker = "<!-- generated by prepare-cache-qa.mjs; temporary manual QA -->"
if (process.argv[3] === "--clean") {
  for (const html of htmlFiles) {
    let source
    try { source = await readFile(html, "utf8") } catch { source = undefined }
    if (source && !source.startsWith(marker)) throw new Error("Refusing to remove an unmarked HTML file.")
    if (source) await rm(html)
  }
  for (const path of copies) await rm(path, { recursive:true, force:true })
  console.log("Removed generated manual QA files.")
} else {
  for (const path of [...htmlFiles,...copies]) {
    try { await access(path) } catch { continue }
    throw new Error(`Refusing to overwrite ${path}; clean a previous generated run first.`)
  }
  const baseline = process.argv[3] ?? "HEAD"
  const revision = execFileSync("git", ["rev-parse", "--verify", `${baseline}^{commit}`], {cwd:repo,encoding:"utf8"}).trim()
  const archive = execFileSync("git", ["archive",revision,...packages.map(name => `packages/${name}/src`)], {cwd:repo,maxBuffer:32*1024*1024})
  const temp = await mkdtemp(join(tmpdir(),"adapter-cache-baseline-"))
  const made = []
  try {
    execFileSync("tar",["-x","-C",temp],{input:archive})
    for (const [index,name] of packages.entries()) {
      await mkdir(copies[index]);made.push(copies[index])
      await cp(join(temp,"packages",name,"src"),copies[index],{recursive:true})
    }
    // Baseline adapters and workers must use the baseline shared tool/constraint code too.
    for (const name of ["webgl", "transformers-js"]) {
      for (const file of ["adapter.ts", "worker.ts"]) {
        const path = join(repo,"packages",name,".cache-qa-baseline",file)
        const source = await readFile(path,"utf8")
        await writeFile(path,source.replaceAll('"@tanstack-ai-browser/structured-output"','"../../structured-output/.cache-qa-baseline/index.ts"'))
      }
    }
    const rootUrl = `/@fs/${repo}/`
    for (const [index,[,templateName]] of pages.entries()) {
      const template = await readFile(join(here,templateName),"utf8")
      const text = template.replace("__CASES_URL__",JSON.stringify(rootUrl+"packages/transformers-js/bench/cache-cases.ts"))
        .replace("__ROOT_URL__",JSON.stringify(rootUrl))
        .replace("__WORKER_URL__",JSON.stringify(rootUrl+"packages/webgl/bench/mem-worker.ts"))
      await writeFile(htmlFiles[index],marker+"\n"+text,{flag:"wx"})
      made.push(htmlFiles[index])
    }
    console.log(`Baseline ${revision}. Open /__adapter-cache-qa.html on this app's existing Vite dev server. No inference runs until Run benchmark.`)
  } catch(error) {
    for(const path of made)await rm(path,{recursive:true,force:true})
    throw error
  } finally { await rm(temp,{recursive:true,force:true}) }
}
